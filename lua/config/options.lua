-- Line Numbers
vim.opt.number = true         -- Shows absolute line numbers on the left
vim.opt.relativenumber = true -- Shows relative line numbers (highly recommended for Neovim)

-- A few other highly recommended defaults:
vim.opt.mouse = "a"           -- Enables your mouse to click and scroll
vim.opt.clipboard = "unnamedplus" -- Syncs Neovim's clipboard with your system clipboard (so Ctrl+C / Ctrl+V work)
vim.opt.tabstop = 4           -- Sets tabs to 4 spaces
vim.opt.shiftwidth = 4        -- Sets indentations to 4 spaces
vim.opt.expandtab = true      -- Converts tabs to spaces
